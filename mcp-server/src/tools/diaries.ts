import { readFileSync } from 'node:fs';
import type { McpServer } from '@modelcontextprotocol/server';
import * as z from 'zod';
import { listAccounts, readCategory, resolveAccount } from '../account/store.ts';
import type { DiariesData, DiaryTier } from '../account/types.ts';
import { freshness } from '../format.ts';
import { pageUrl } from '../wiki/client.ts';
import { fail, NO_EXPORT_HELP, READ_ONLY_LOCAL, safe, text } from './util.ts';

interface DiaryTask {
  region: string;
  tier: DiaryTier;
  task: string;
  varp?: number;
  bit?: number;
  varbit?: number;
  notDoneOp?: string;
  value?: number;
}

// Generated by scripts/gen-diary-tasks.mjs from Quest Helper (BSD-2-Clause).
const TASKS: DiaryTask[] = JSON.parse(readFileSync(new URL('../../data/diary-tasks.json', import.meta.url), 'utf8')).tasks;
const TIERS: DiaryTier[] = ['easy', 'medium', 'hard', 'elite'];
const REGIONS = [...new Set(TASKS.map((t) => t.region))];

/** Quest Helper conditions are "not done yet" checks; a task is done when its condition is false. */
function isDone(task: DiaryTask, vars: NonNullable<DiariesData['taskVars']>): boolean | undefined {
  if (task.varp !== undefined && task.bit !== undefined) {
    const v = vars.varps[String(task.varp)];
    return v === undefined ? undefined : ((v >>> task.bit) & 1) === 1;
  }
  if (task.varbit !== undefined && task.value !== undefined) {
    const v = vars.varbits[String(task.varbit)];
    if (v === undefined) return undefined;
    const notDone = {
      EQUAL: v === task.value,
      NOT_EQUAL: v !== task.value,
      LESS: v < task.value,
      LESS_EQUAL: v <= task.value,
      GREATER: v > task.value,
      GREATER_EQUAL: v >= task.value,
    }[task.notDoneOp ?? 'EQUAL'];
    return notDone === undefined ? undefined : !notDone;
  }
  return undefined;
}

const diaryPage = (region: string) => pageUrl(`${region} Diary`);

export function registerDiaryTools(server: McpServer): void {
  server.registerTool(
    'get_achievement_diaries',
    {
      title: 'Achievement diaries',
      description:
        "The player's Achievement Diary progress. Without filters: tasks done per region and tier (e.g. Varrock medium 7/13). With `region` and/or `tier`: the individual tasks and whether each is done — use this to suggest which diary tasks to do next.",
      inputSchema: z.object({
        rsn: z.string().max(12).optional(),
        region: z.enum(REGIONS as [string, ...string[]]).optional(),
        tier: z.enum(['easy', 'medium', 'hard', 'elite']).optional(),
        status: z.enum(['all', 'incomplete', 'complete']).default('all').describe('Task list filter.'),
      }),
      annotations: READ_ONLY_LOCAL,
    },
    safe('get_achievement_diaries', async ({ rsn, region, tier, status }) => {
      const acct = await resolveAccount(rsn);
      if (!acct) {
        const known = (await listAccounts()).map((a) => a.rsn);
        return fail(rsn ? `No exported data for "${rsn}". Known accounts: ${known.join(', ') || 'none'}.` : NO_EXPORT_HELP);
      }
      const env = await readCategory<DiariesData>(acct, 'diaries');
      if (!env) return fail(NO_EXPORT_HELP);
      const d = env.data;
      const head = `Achievement diaries for ${acct.rsn}, ${freshness(env.capturedAt)}. ${d.tiersComplete}/${d.tiersTotal} tiers complete.`;
      const progress = (r: DiariesData['regions'][number], t: DiaryTier) => {
        const x = r.tiers[t];
        if (!x) return '?';
        if (x.complete) return '✓';
        return x.tasksTotal ? `${x.tasksDone ?? 0}/${x.tasksTotal}` : '—';
      };

      if (!region && !tier) {
        const rows = d.regions.map((r) => `| ${r.region} | ${TIERS.map((t) => progress(r, t)).join(' | ')} |`);
        return text(
          [
            head,
            '',
            '| Region | Easy | Medium | Hard | Elite |',
            '| --- | --- | --- | --- | --- |',
            ...rows,
            '',
            '✓ = tier complete (reward may be unclaimed); n/m = tasks done. Ask with a region/tier for the task list.',
          ].join('\n'),
        );
      }

      if (!d.taskVars) {
        return fail('Task-level data needs exporter plugin 0.5.0 or newer: restart RuneLite with the shortcut and log in.');
      }
      const out = [head];
      for (const reg of region ? [region] : REGIONS) {
        const r = d.regions.find((x) => x.region === reg);
        for (const t of tier ? [tier] : TIERS) {
          const tasks = TASKS.filter((x) => x.region === reg && x.tier === t);
          const decoded = tasks.map((x) => ({ task: x.task, done: isDone(x, d.taskVars!) }));
          const shown = decoded.filter((x) => status === 'all' || (status === 'complete' ? x.done === true : x.done !== true));
          const gameDone = r?.tiers[t]?.tasksDone;
          const ourDone = decoded.filter((x) => x.done).length;
          out.push('', `### ${reg} ${t} — ${r?.tiers[t]?.complete ? 'complete' : `${gameDone ?? ourDone}/${r?.tiers[t]?.tasksTotal ?? tasks.length} tasks`}`);
          if (gameDone !== undefined && gameDone !== ourDone) {
            out.push(`(The game counts ${gameDone} done but the task list decodes ${ourDone}; individual ticks may be slightly off.)`);
          }
          out.push(shown.length ? shown.map((x) => `- ${x.done === true ? '✓' : x.done === false ? '☐' : '?'} ${x.task}`).join('\n') : 'Nothing to show.');
        }
        out.push(`Task details and requirements: ${diaryPage(reg)}`);
      }
      out.push('', 'Task names: Quest Helper (BSD-2-Clause). Use wiki_read on "<Region> Diary" for exact task requirements.');
      return text(out.join('\n'));
    }),
  );
}
